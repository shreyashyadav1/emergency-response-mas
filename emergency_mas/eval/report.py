"""Turn the run table into docs/RESULTS.md and one figure. Every number comes from the runs CSV."""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from .runner import POLICY_LABEL
from .stats import bootstrap_ci, paired

STRESS_ORDER = ["low", "medium", "high"]
POLICY_ORDER = ["B0", "B1", "M1", "M2"]
COLORS = {"B0": "#b9b8b2", "B1": "#7d7c76", "M1": "#86b6ef", "M2": "#1c5cab"}   # baselines gray, agents blue
OUTCOMES = [
    ("weighted_survival", "Weighted survival", 3),
    ("expected_survivors", "Expected survivors", 1),
    ("red_survivors", "RED survivors", 2),
    ("victims_served", "Victims reaching care", 1),
    ("unserved_critical_incidents", "Critical incidents with a RED patient never treated", 2),
    ("mean_first_response_min", "First unit on scene (min)", 1),
    ("ambulance_utilization", "Ambulance utilization", 2),
    ("er_bay_utilization", "ER bay utilization", 2),
    ("ramp_wait_min", "Ambulance minutes waiting at ER doors", 0),
]


def _fmt(x: float, digits: int) -> str:
    return f"{x:.{digits}f}"


def _mean_ci(values: pd.Series, digits: int) -> str:
    v = values.dropna().to_numpy(dtype=float)
    if len(v) == 0:
        return "n/a"
    lo, hi = bootstrap_ci(v)
    return f"{_fmt(v.mean(), digits)} ({_fmt(lo, digits)} to {_fmt(hi, digits)})"


def _table(headers: list[str], rows: list[list[str]]) -> list[str]:
    return ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers), *("| " + " | ".join(r) + " |" for r in rows), ""]


def figure(frame: pd.DataFrame, path: Path, theme: str = "urban_mci") -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams["font.family"] = ["Arial", "Helvetica", "DejaVu Sans"]
    ink, muted, grid = "#0f2233", "#52606d", "#e1e4e9"
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.9), dpi=200)
    panels = [("weighted_survival", "Weighted survival (higher is better)"), ("red_survivors", "RED survivors per scenario")]
    sub = frame[frame.theme == theme]
    for ax, (metric, title) in zip(axes, panels):
        for k, policy in enumerate(POLICY_ORDER):
            xs, ys, los, his = [], [], [], []
            for s, stress in enumerate(STRESS_ORDER):
                v = sub[(sub.stress == stress) & (sub.policy == policy)][metric].to_numpy(dtype=float)
                if len(v) == 0:
                    continue
                lo, hi = bootstrap_ci(v)
                xs.append(s + (k - 1.5) * 0.17)
                ys.append(v.mean())
                los.append(v.mean() - lo)
                his.append(hi - v.mean())
            ax.errorbar(xs, ys, yerr=[los, his], fmt="o", ms=7, color=COLORS[policy], ecolor=COLORS[policy],
                        elinewidth=2, capsize=0, label=POLICY_LABEL[policy], markeredgecolor="white", markeredgewidth=1.5)
        ax.set_xticks(range(len(STRESS_ORDER)), [s.capitalize() + " stress" for s in STRESS_ORDER], color=ink)
        ax.set_title(title, loc="left", fontsize=11, color=ink)
        ax.grid(axis="y", color=grid, linewidth=0.8)
        ax.set_axisbelow(True)
        for side in ("top", "right", "left"):
            ax.spines[side].set_visible(False)
        ax.spines["bottom"].set_color("#c3c2b7")
        ax.tick_params(colors=muted, length=0)
    axes[0].legend(loc="lower left", frameon=False, fontsize=9, labelcolor=ink)
    fig.text(0.01, 0.01, f"Mean of {sub.seed.nunique()} seeds per stress level, urban theme. Bars are 95% bootstrap intervals.",
             fontsize=8.5, color=muted)
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, facecolor="white")
    plt.close(fig)


def build_report(frame: pd.DataFrame, figure_path: Path | None = None, figure_link: str | None = None) -> str:
    L: list[str] = ["# Results", "",
                    "Generated by `python -m emergency_mas.eval report` from `results/runs.csv`. Do not edit by hand.", ""]
    n_seeds = frame.seed.nunique()
    L += [f"Every policy ran on the same scenarios: {frame.groupby(['theme', 'stress']).ngroups} settings x {n_seeds} seeds, "
          f"{len(frame)} runs in total. Differences are paired by seed. Brackets are 95% bootstrap intervals; p-values are "
          "Wilcoxon signed-rank tests.", ""]
    L += ["Policies: " + "; ".join(f"**{k}** {POLICY_LABEL[k].split(' ', 1)[1]}" for k in POLICY_ORDER) + ".", ""]
    if figure_link:
        L += [f"![Weighted survival and RED survivors by stress level]({figure_link})", ""]

    urban = frame[frame.theme == "urban_mci"]
    L += ["## Headline", ""]
    best = []
    for stress in STRESS_ORDER:
        g = urban[urban.stress == stress]
        if g.empty:
            continue
        means = g.groupby("policy")["weighted_survival"].mean()
        best_base = "B0" if means.get("B0", -1) >= means.get("B1", -1) else "B1"
        d = paired(g, "weighted_survival", "M2", best_base, by=("stress",)).iloc[0]
        e = paired(g, "expected_survivors", "M2", best_base, by=("stress",)).iloc[0]
        neg = paired(g, "weighted_survival", "M2", "M1", by=("stress",)).iloc[0]
        best.append([stress, best_base, f"{d['diff']:+.3f} [{d.ci_low:+.3f}, {d.ci_high:+.3f}]", f"{d.a_better_share:.0%}",
                     f"{d.p_value:.1g}", f"{e['diff']:+.2f} [{e.ci_low:+.2f}, {e.ci_high:+.2f}]",
                     f"{neg['diff']:+.3f} [{neg.ci_low:+.3f}, {neg.ci_high:+.3f}]", f"{neg.p_value:.1g}"])
    L += _table(["Stress", "Best baseline", "M2 minus it: weighted survival", "Seeds where M2 is better", "p",
                 "M2 minus it: expected survivors", "Negotiation effect (M2 minus M1)", "p"], best)

    for stress in STRESS_ORDER:
        g = urban[urban.stress == stress]
        if g.empty:
            continue
        L += [f"## Urban theme, {stress} stress", ""]
        rows = []
        for metric, label, digits in OUTCOMES:
            rows.append([label] + [_mean_ci(g[g.policy == p][metric], digits) for p in POLICY_ORDER])
        L += _table(["Outcome (mean, 95% interval)"] + POLICY_ORDER, rows)

    L += ["## Paired differences, weighted survival", ""]
    rows = []
    for a, b in (("M2", "B0"), ("M2", "B1"), ("M2", "M1"), ("M1", "B1")):
        for _, r in paired(frame, "weighted_survival", a, b).iterrows():
            rows.append([f"{a} - {b}", r.theme, r.stress, f"{r['diff']:+.3f} [{r.ci_low:+.3f}, {r.ci_high:+.3f}]",
                         f"{r.a_better_share:.0%}", f"{r.p_value:.1g}"])
    L += _table(["Comparison", "Theme", "Stress", "Difference", f"{'Seeds better'}", "p"], rows)

    other = frame[frame.theme != "urban_mci"]
    if not other.empty:
        L += ["## Other themes", ""]
        rows = []
        for (theme, stress), g in other.groupby(["theme", "stress"]):
            rows.append([f"{theme} / {stress}"] + [_mean_ci(g[g.policy == p]["weighted_survival"], 3) for p in POLICY_ORDER])
        L += _table(["Weighted survival"] + POLICY_ORDER, rows)

    m2 = frame[frame.policy == "M2"]
    if "agent_victims_bias" in m2:
        L += ["## Incident Assessment Agent against the raw caller report", "",
              "First estimate of each incident, before any unit is on scene. Mean over all M2 runs.", ""]
        rows = []
        for label, key in (("Victim count bias", "victims_bias"), ("Victim count RMSE", "victims_rmse"),
                           ("RED count bias", "red_bias"), ("RED count RMSE", "red_rmse"),
                           ("Rank correlation with oracle urgency", "rank_corr")):
            rows.append([label, f"{m2[f'report_{key}'].mean():.3f}", f"{m2[f'agent_{key}'].mean():.3f}"])
        L += _table(["", "Caller report", "Assessment agent"], rows)

    if "messages" in m2:
        L += ["## Communication and negotiation (M2, per run)", ""]
        cols = [("messages", "Messages"), ("messages_conflict_notice", "Unit conflicts"),
                ("messages_counter_proposal", "Hospital counter-offers"), ("messages_staff_request", "Staff requests"),
                ("staff_moves", "Staff moved (pool and loans)"), ("diversions", "Diversions from full ER doors"),
                ("surges_opened", "Surge openings")]
        rows = []
        for stress in STRESS_ORDER:
            g = m2[(m2.theme == "urban_mci") & (m2.stress == stress)]
            if g.empty:
                continue
            rows.append([stress] + [f"{g[c].mean():.1f}" if c in g else "0" for c, _ in cols])
        L += _table(["Stress"] + [label for _, label in cols], rows)

    L += ["## Reproduce", "",
          "```bash",
          f".venv/bin/python -m emergency_mas.eval run --seeds {n_seeds}",
          ".venv/bin/python -m emergency_mas.eval report",
          "```", "",
          "The simulator and all four policies are deterministic, so the same command gives the same table.", "",
          "## Limits", "",
          "- The world is synthetic and its parameters are illustrative (see ASSUMPTIONS.md). The comparison between "
          "policies is the result, not the absolute survival numbers.",
          "- These runs use the rules backend of the agents. The OpenAI Agents SDK agents (M3) are compared with M2 and B0 "
          "on 30 seeds in LLM_RESULTS.md.",
          "- Victims still waiting when the 4-hour horizon ends are scored as if care started at the horizon, for every policy.",
          ""]
    return "\n".join(L)
